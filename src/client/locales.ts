/** Dictionary key union. */
export type PromptEnhanceKey = keyof typeof zh

/** Every shipped key, for the defensive lookup below (zh is the source of truth). */
const KNOWN_KEYS: ReadonlySet<string> = new Set(Object.keys(zh))

/**
 * Whether one string is a key this namespace actually ships.
 *
 * The panel resolves the error detail line through a dictionary key when the
 * browser half supplies one (`EnhanceError.detailKey`). That value reaches the
 * panel from an object the browser built, but a wrong key would otherwise render
 * as the raw key text inside the dialog, so the lookup is verified against the
 * shipped key set instead of trusting the type of a `string` field.
 * @param value - the candidate key.
 * @returns true when the key exists in the namespace.
 */
export function isPromptEnhanceKey(value: string): value is PromptEnhanceKey {
  return KNOWN_KEYS.has(value)
}

